/**
 * Translates an in-game callout to the target language.
 * Defaults to Brazilian Portuguese callout slang when lang is 'pt-BR' or 'pt'.
 */
export function localizeCallout(rawCallout: string | undefined | null, lang: Language): string {
  if (!rawCallout) return '';
  const clean = rawCallout.trim();
  if (lang === 'en') return clean;

  const dict = lang === 'pt-BR' ? BRAZILIAN_CALLOUTS : SPANISH_CALLOUTS;
  const lower = clean.toLowerCase();

  // 1. Direct exact lookup
  if (dict[lower]) {
    return dict[lower];
  }

  // 2. Tokenized / partial replacement sorted by phrase length descending
  const keys = Object.keys(dict).sort((a, b) => b.length - a.length);
  let result = clean;
  for (const key of keys) {
    const escaped = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const regex = new RegExp(`\\b${escaped}\\b`, 'gi');
    if (regex.test(result)) {
      result = result.replace(regex, dict[key]);
    }
  }

  return result;
}
